def plural(count, one, few, many):
    """1 випадок, 2 випадки, 5 випадків."""
    tail, last = count % 100, count % 10
    if 11 <= tail <= 14:
        return "%s %s" % (count, many)
    if last == 1:
        return "%s %s" % (count, one)
    if 2 <= last <= 4:
        return "%s %s" % (count, few)
    return "%s %s" % (count, many)


def money(value, missing="не зафіксовано"):
    """30 000,00 - як пише бухгалтер."""
    if value is None:
        return missing
    return "{:,.2f}".format(value).replace(",", " ").replace(".", ",")


def line_names(ruleset):
    return {rule["code"]: rule["name"] for rule in ruleset.rules}


def rows_for(scenario, result, names):
    """Рядки таблиці: код, назва, число системи, число перевірки, чи розійшлися."""
    expect = {code: float(value) for code, value in (scenario.get("expect") or {}).items()}
    got = result.dict()
    order = [rule for rule in names]
    seen, out = set(), []
    for code in order:
        if code not in got and code not in expect:
            continue
        mine = got.get(code, 0.0)
        theirs = expect.get(code)
        if abs(mine) < TOLERANCE and theirs is None:
            continue
        seen.add(code)
        out.append((names.get(code, code), theirs, mine,
                    theirs is not None and abs(theirs - mine) >= TOLERANCE))
    for code, theirs in sorted(expect.items()):
        if code not in seen:
            out.append((names.get(code, code), theirs, got.get(code, 0.0),
                        abs(theirs - got.get(code, 0.0)) >= TOLERANCE))
    return out


def move_rows(scenario, moves):
    golden, mine = {}, {}
    for move in scenario.get("moves") or []:
        key = "%s %s" % (move["side"], move["account"])
        golden[key] = golden.get(key, 0.0) + float(move["amount"])
    for move in moves:
        key = "%s %s" % (move["side"], move["account"])
        mine[key] = mine.get(key, 0.0) + float(move["amount"])
    if not golden:
        return []
    out = []
    for key in sorted(set(golden) | set(mine), key=lambda k: (k[0] != "Д", k)):
        a, b = golden.get(key), mine.get(key)
        out.append((key, a, b, a is None or b is None or abs(a - b) >= TOLERANCE))
    return out


def block(scenario, result, moves, names):
    lines = rows_for(scenario, result, names)
    accounts = move_rows(scenario, moves)
    differs = any(row[3] for row in lines) or any(row[3] for row in accounts)
    text = ["## Сценарій %s. %s" % (scenario["id"], scenario["title"]), ""]
    if differs:
        text += ["> Два боки рахують по-різному. Дивіться відкрите питання під таблицею.", ""]
    text += [FACTS[scenario["id"]], "",
             "| Рядок | Рахує система | Рахує незалежна перевірка | Підтверджую / моє число |",
             "| --- | ---: | ---: | --- |"]
    for name, theirs, mine, bad in lines:
        mark = " ‹різниця›" if bad else ""
        text.append("| %s | %s | %s%s |  |" % (name, money(theirs), money(mine), mark))
    if accounts:
        text.append("| **Проводки** |  |  |  |")
        for key, theirs, mine, bad in accounts:
            mark = " ‹різниця›" if bad else ""
            text.append("| %s | %s | %s%s |  |"
                        % (key, money(theirs, "рядка немає"), money(mine, "рядка немає"), mark))
    question = QUESTIONS.get(scenario["id"])
    if question:
        text += ["", question]
    text.append("")
    return "\n".join(text), differs


def main():
    params = Params.load(os.path.join(CORE, "data", "params-ua.json"))
    ruleset = RuleSet.load(os.path.join(CORE, "data", "rules-ua.json"))
    cpi = load_cpi(os.path.join(CORE, "data", "cpi-ua.json"))
    data = load_scenarios(GOLDEN)
    names = line_names(ruleset)

    blocks, unsupported = [], []
    for scenario in data["scenarios"]:
        try:
            slip = build(scenario, cpi)
        except Unsupported as reason:
            unsupported.append((scenario, str(reason)))
            continue
        result = compute(slip, params, ruleset)
        blocks.append((scenario["id"],) + block(scenario, result, build_moves(result), names))

    differing = [b for b in blocks if b[2]]
    same = [b for b in blocks if not b[2]]
    head = HEADER % (plural(len(blocks) + len(unsupported), "сценарій", "сценарії", "сценаріїв"),
                     plural(len(differing), "випадок", "випадки", "випадків"),
                     plural(len(same), "випадок", "випадки", "випадків"),
                     plural(len(unsupported), "випадок", "випадки", "випадків"))
    body = [b[1] for b in differing] + [b[1] for b in same]
    if unsupported:
        body.append("## Сценарії, яких незалежна перевірка не рахує\n")
        for scenario, reason in unsupported:
            body.append("- Сценарій %s. %s. Причина: %s\n" % (scenario["id"], scenario["title"], reason))
    with open(OUT, "w", encoding="utf-8") as stream:
        stream.write(head + "\n".join(body) + FOOTER)
    print("Записано %s" % os.path.relpath(OUT, ROOT))
    return 0


