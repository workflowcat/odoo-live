"""Габарит виробу: скільки місць на полиці займає одна штука.

Нативний Odoo міряє місткість інакше: `stock.storage.category` задає ліміт на
конкретний товар або тип упаковки, тобто «на цю полицю влізе 30 двигунів і 12
рам». Комірник же думає простіше - полиця має N місць, дрібниця займає одне,
рама чотири, зібраний дрон шістнадцять. Тому габарит - це три букви на товарі, а
не довідник категорій зберігання. Нативні категорії від цього нікуди не діваються
і працюють паралельно: вони обмежують розкладання, наш габарит лише рахує
заповнення для карти складу.

Порожній габарит рахується як S: товар без позначки займає одне місце.
"""
from odoo import fields, models

# Скільки місць займає одна одиниця товару. Числа з вимоги інтерфейсу: S/M/L = 1/4/16.
UA_SIZE_SLOTS = {"s": 1, "m": 4, "l": 16}


class ProductTemplate(models.Model):
    _inherit = "product.template"

    ua_size = fields.Selection(
        [("s", "S - дрібне"), ("m", "M - середнє"), ("l", "L - велике")],
        string="Габарит",
        default="s",
        help="Скільки місць на полиці займає одна одиниця: S - одне, M - чотири, "
             "L - шістнадцять. Порожнє поле рахується як S.",
    )

    def _ua_slots(self):
        """Місць на одну одиницю товару."""
        self.ensure_one()
        return UA_SIZE_SLOTS.get(self.ua_size, 1)
