# -*- coding: utf-8 -*-
"""Маркер нульових груп ПДВ.

Нативний l10n_ua дає податки 0 %, «звільнено» і «не є об'єктом», але всі три
мають однакову ставку 0 % і відрізнити їх у коді нічим. Для податкової
накладної це принципово: графа 8 просить код ставки 901 (експорт),
902 (0 % на митній території) чи 903 (звільнено), а для звільнених рядків
ще й код пільги в графі 9.

Тому додаємо на групу податків одне поле-маркер і вішаємо групи на нативні
нульові податки (data/шаблон + post_init_hook). Ніякого пошуку за назвою.
"""
from odoo import fields, models


class AccountTaxGroup(models.Model):
    _inherit = "account.tax.group"

    x_ua_vat_zero_kind = fields.Selection(
        selection=[
            ("export", "0 % експорт"),
            ("exempt", "Звільнено від ПДВ"),
            ("not_object", "Не є об'єктом оподаткування"),
        ],
        string="Вид нульової ставки (ПДВ, Україна)",
        help="Чим саме є нульовий рядок для податкової накладної: "
             "експорт (код ставки 901), звільнення (903, потрібен код пільги) "
             "чи операція поза об'єктом оподаткування.",
    )
