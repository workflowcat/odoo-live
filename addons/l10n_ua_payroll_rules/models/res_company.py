from odoo import fields, models


class ResCompany(models.Model):
    _inherit = "res.company"

    ua_vacation_opening_date = fields.Date("Дата впровадження обліку відпусток",
                                           help="Типова дата впровадження для працівників, у яких власна дата не задана")

    # Дія Сіті (ЗУ «Про стимулювання розвитку цифрової економіки в Україні»): пільгові ставки
    # для працівників і гіг-спеціалістів діють з місяця, наступного за набуттям статусу,
    # і лише в місяцях, коли резидент відповідає вимогам (ua.diia.city.month).
    ua_dc_resident = fields.Boolean("Резидент Дія Сіті")
    ua_dc_since = fields.Date("Статус резидента з",
                              help="Дата внесення до реєстру Дія Сіті. Пільгові ставки - з першого числа наступного місяця.")
    ua_dc_until = fields.Date("Статус припинено", help="Порожньо - статус чинний")
