"""Реквізити підприємства, яких немає в нативному Odoo.

ЄДРПОУ - нативний `company_registry`, ІПН платника ПДВ - нативний `vat`,
адреса і банківські рахунки - нативні поля партнера компанії. Додаємо лише те,
чого в Odoo немає взагалі: хто підписує папери і на підставі чого.

Увага на перетин: поля `ua_director_name` і `ua_accountant_name` уже оголошує
`l10n_ua_payroll_reports`. Первинка не має права залежати від зарплати, тому
оголошення повторене тут з тими самими назвами і типом - Odoo зливає такі
оголошення в одне поле і одну колонку. Коли модулі зведуть докупи, це місце
треба буде залишити одне.
"""
from odoo import fields, models


class ResCompany(models.Model):
    _inherit = "res.company"

    ua_director_name = fields.Char("Керівник (ПІБ)")
    ua_accountant_name = fields.Char("Головний бухгалтер (ПІБ)")

    ua_acts_on_basis = fields.Char(
        "Діє на підставі", default="Статуту",
        help="Чим уповноважений підписант: Статуту, довіреності № ... від ..., "
             "наказу. Друкується в шапці акта і накладної.")

    def _ua_docs_bank(self):
        """Банківський рахунок компанії для друку. Перший з картки партнера."""
        self.ensure_one()
        return self.partner_id.bank_ids[:1]
