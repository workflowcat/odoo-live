"""Стаття калькуляції на товарі і ставки на робочому центрі.

Постанова КМУ № 309 розводить матеріали (01) і покупні комплектуючі (02): на покупні
прибуток нараховується за окремим, меншим нормативом. Тому стаття стоїть на кожному
товарі, що входить у специфікацію. Паливо й енергію на технологічні цілі (03) можна
вести і товаром (газ, дизель), і ставкою за годину робочого центру.

Робочий центр Odoo знає одну вартість години (costs_hour). Для статей 309 її мало:
основна зарплата (04) і енергія (03) ідуть окремими ставками, а costs_hour лишається
утриманням і експлуатацією обладнання (07).
"""
from odoo import fields, models

COST_ITEMS = [
    ("01", "01 Сировина і матеріали"),
    ("02", "02 Покупні комплектуючі, напівфабрикати, роботи і послуги сторонніх"),
    ("03", "03 Паливо й енергія на технологічні цілі"),
]


class ProductTemplate(models.Model):
    _inherit = "product.template"

    ua_cost_item = fields.Selection(
        COST_ITEMS, "Стаття калькуляції", default="01",
        help="Стаття постанови КМУ № 309, на яку товар лягає в калькуляції ціни.")
    ua_warranty_months = fields.Integer(
        "Гарантія, місяців", help="Друкується в паспорті виробу.")


class MrpWorkcenter(models.Model):
    _inherit = "mrp.workcenter"

    ua_wage_hour = fields.Float(
        "Основна зарплата за годину",
        help="Стаття 04: основна зарплата виробничих робітників за годину роботи центру.")
    ua_energy_hour = fields.Float(
        "Енергія за годину",
        help="Стаття 03: паливо й енергія на технологічні цілі за годину роботи центру.")
