"""Списання активу: режим проводки за замовчуванням.

OCA має два режими зняття з обліку - «залишкова вартість» (усе, що не
замортизовано, йде на окремий рахунок) і «прибуток/збиток від продажу».
Перший за замовчуванням увімкнено лише для Франції. В Україні при
списанні об'єкта (ОЗ-3) залишкову вартість відносять на 976 «Списання
необоротних активів», тобто це саме перший режим. Додаємо Україну до
списку країн - один рядок, логіка OCA не змінюється.
"""
from odoo import models


class AccountAssetRemove(models.TransientModel):
    _inherit = "account.asset.remove"

    def _residual_value_regime_countries(self):
        return super()._residual_value_regime_countries() + ["UA"]
