# -*- coding: utf-8 -*-
"""Рядок розділу IV форми № 5 і спосіб оцінки - на рахунку фінансових інвестицій (14, 352).

Вид інвестиції (асоційоване чи дочірнє підприємство, частки, акції, облігації) план рахунків не
розрізняє, тож бухгалтер ставить рядок на субрахунку. Без нього: 141 - асоційовані (зі
зауваженням у примітках), решта - інші."""
from odoo import fields, models

INVESTMENT_ROWS = [
    ("350", "350 Асоційовані підприємства (метод участі в капіталі)"),
    ("360", "360 Дочірні підприємства (метод участі в капіталі)"),
    ("370", "370 Спільна діяльність (метод участі в капіталі)"),
    ("380", "380 Частки і паї у статутному капіталі інших підприємств"),
    ("390", "390 Акції"),
    ("400", "400 Облігації"),
    ("410", "410 Інші"),
]
INVESTMENT_BASIS = [
    ("cost", "За собівартістю"),
    ("fair", "За справедливою вартістю"),
    ("amortized", "За амортизованою собівартістю"),
]


class AccountAccount(models.Model):
    _inherit = "account.account"

    ua_investment_row = fields.Selection(
        INVESTMENT_ROWS, string="Рядок розділу IV форми № 5",
        help="Лише для рахунків фінансових інвестицій 14 і 352. Порожньо: 141 - асоційовані "
             "підприємства, решта - інші.")
    ua_investment_basis = fields.Selection(
        INVESTMENT_BASIS, string="Оцінка інвестиції у формі № 5",
        help="Рядки 421-426: як відображено інвестицію. Порожньо - за собівартістю.")
