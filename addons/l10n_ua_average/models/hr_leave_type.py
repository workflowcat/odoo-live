# -*- coding: utf-8 -*-
"""Вид відпустки: підстава нарахування за українським законом і одиниця обліку днів.

Два поля, обидва читає генератор нарахувань (hr.employee._ua_ensure_leave_allocations) і
розрахунок залишків:

- ua_alloc_basis - за що саме нараховуються дні. Порожнє означає «без нарахування»: лікарняний,
  відпустка без збереження, декрет, навчальна, відрядження. Такі види лишаються з
  requires_allocation = False, і рідна перевірка залишку їх не чіпає.
- ua_calendar_days - дні відпустки рахуються календарні, а не робочі. Українські відпустки
  надаються в календарних днях (ст. 5 ЗУ «Про відпустки»), рідний Odoo рахує дні за графіком
  роботи. Прапорець вмикає перерахунок у hr.leave._get_durations, щоб нарахування списувались
  тими самими днями, якими їх надано.
"""
from odoo import fields, models

UA_ALLOC_BASIS = [
    ("work_year", "За робочий рік, не згорає"),
    ("year_carry", "За календарний рік, переноситься"),
    ("year", "За календарний рік, не переноситься"),
]


class HrLeaveType(models.Model):
    _inherit = "hr.leave.type"

    ua_alloc_basis = fields.Selection(
        UA_ALLOC_BASIS, "Підстава нарахування (Україна)",
        help="Порожнє - дні не нараховуються (лікарняний, декрет, відрядження, без збереження). "
             "«За робочий рік» - щорічна основна відпустка від дати прийняття, невикористане не згорає "
             "(ст. 6, 10 ЗУ «Про відпустки»). «За календарний рік, переноситься» - соціальна відпустка "
             "на дітей (ст. 19). «За календарний рік, не переноситься» - додаткова УБД (ст. 16-2).")
    ua_calendar_days = fields.Boolean(
        "Рахувати календарні дні", default=False,
        help="Дні заявки рахуються календарні (ст. 5 ЗУ «Про відпустки»), а не робочі за графіком. "
             "Святкові дні на час воєнного стану не переносяться, тому з періоду нічого не виключається.")
