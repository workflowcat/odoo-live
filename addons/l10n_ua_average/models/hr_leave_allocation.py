# -*- coding: utf-8 -*-
"""Нарахування днів відпустки: два поля-мітки, щоб генератор упізнавав власні записи.

Самі нарахування - рідні hr.leave.allocation. Нічого в їхній поведінці ми не міняємо: залишок,
віджет і заборона просити більше за залишок лишаються ті, що в hr_holidays. Мітки потрібні
тільки для ідемпотентності: генератор шукає свій запис за парою (ua_source, ua_period_start)
і оновлює його, а не створює другий.
"""
from odoo import fields, models

UA_SOURCE = [
    ("rule", "Нараховано за правилом"),
    ("opening", "Залишок на дату впровадження"),
    ("transition", "Коригування при переході"),
]


class HrLeaveAllocation(models.Model):
    _inherit = "hr.leave.allocation"

    ua_source = fields.Selection(
        UA_SOURCE, "Звідки нарахування", index=True, copy=False,
        help="Порожнє - нарахування завела людина руками; генератор такі не чіпає.")
    ua_period_start = fields.Date(
        "Початок періоду нарахування", index=True, copy=False,
        help="Початок робочого року (щорічна) або 1 січня (відпустки за календарний рік). "
             "Разом із «Звідки нарахування» - ключ, за яким генератор знаходить свій запис.")
