"""Кроки операції і пункти перевірки ВТК простим текстом.

Що дає нативний CE 19. Операція маршруту (`mrp.routing.workcenter`) має назву,
робочий центр, порядок (`sequence`), норму часу (`time_cycle_manual`, хвилини) і
рахунок циклів (`time_cycle`, `time_total`). Рядок специфікації має
`operation_id` «Споживається в операції» - поле нативне, живе в самому `mrp`, а
не в Enterprise `mrp_workorder`; у формі специфікації воно під групою
`mrp.group_mrp_routings`. Тобто прив'язку «що збираємо на цьому кроці» ставить
голий Odoo, нічого додавати не треба.

Чого нема. Місця під текст: ні опису, ні нотатки, ні аркуша операції - аркуш
(`worksheet`) і контрольні точки якості приходять із Enterprise. Тому два
текстові поля: «Кроки» і «Перевірка», по пункту на рядок. Парсять їх там, де
читають - у `product.template.ua_assembly()`.

Свідоме спрощення: це саме текст, а не модель із рядками. Контрольні точки, що
блокують операцію, - інша задача, і для паперу вона вже вирішена окремим
документом ВТК (`ua.quality.protocol`).
"""
from odoo import fields, models


class MrpRoutingWorkcenter(models.Model):
    _inherit = "mrp.routing.workcenter"

    ua_steps = fields.Text(
        string="Кроки",
        help="Порядок дій на операції, по кроку в рядок.",
    )
    ua_checks = fields.Text(
        string="Перевірка",
        help="Пункти перевірки ВТК на цій операції, по пункту в рядок.",
    )
