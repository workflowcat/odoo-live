"""Ліміт залишку готівки в касі.

Ліміт підприємство встановлює власним наказом (розділ II Положення НБУ № 148 від
29.12.2017). Розмір у кожної компанії свій і переглядається, тому це поле компанії,
а не константа в коді. Нуль означає, що ліміт не встановлено і аркуш касової книги
не попереджає про перевищення.
"""
from odoo import fields, models


class ResCompany(models.Model):
    _inherit = "res.company"

    ua_cash_limit = fields.Monetary(
        "Ліміт каси",
        currency_field="currency_id",
        help="Найбільший залишок готівки в касі на кінець дня за наказом підприємства. "
             "Понадлімітну готівку належить здати в банк. Нуль - ліміт не встановлено.",
    )
