"""Прапорець «не дохід» на платежі.

Не все, що прийшло на рахунок, є доходом єдинника: кредит банку, поворотна
фінансова допомога, повернена протягом 12 місяців, власні кошти підприємця,
внесені на свій рахунок, - усе це до доходу не включається (п. 292.11 ПКУ і
роз'яснення ДПС щодо власних коштів). Прапорець ставить бухгалтер на платежі,
а книга доходів його підхоплює.
"""
from odoo import fields, models


class AccountPayment(models.Model):
    _inherit = "account.payment"

    ua_fop_not_income = fields.Boolean(
        "Не дохід ФОП",
        help="Надходження, яке не є доходом платника ЄП: кредит, поворотна "
             "фінансова допомога, власні кошти підприємця на свій рахунок "
             "(п. 292.11 ПКУ). У книзі доходів рядок лишається, але в "
             "розрахунок ЄП не потрапляє.",
    )

    def write(self, vals):
        res = super().write(vals)
        if "ua_fop_not_income" in vals:
            # Прапорець перемкнули після синхронізації - переставляємо вид рядка.
            self.env["ua.fop.income"]._ua_fop_apply_flag(self)
        return res
